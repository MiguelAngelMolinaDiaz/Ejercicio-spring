package EjercicioActividad3;

public class Console {
    private int idConsola;
    private String nombre;
    private String fabricante;
    private int generacion;

    public int getIdConsola() { return idConsola; }
    public void setIdConsola(int idConsola) { this.idConsola = idConsola; }

    public String getNombre() { return nombre; }
    public void setNombre(String nombre) { this.nombre = nombre; }

    public String getFabricante() { return fabricante; }
    public void setFabricante(String fabricante) { this.fabricante = fabricante; }

    public int getGeneracion() { return generacion; }
    public void setGeneracion(int generacion) { this.generacion = generacion; }
}
